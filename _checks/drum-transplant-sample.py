"""Generate and check the point probe's data. Run with Python, NumPy, SciPy and Node."""
from collections import Counter
from pathlib import Path
import json
import subprocess

import numpy as np
from scipy.sparse import coo_matrix
from scipy.sparse.linalg import eigsh

site = Path(__file__).resolve().parents[1] / "projects/hear-the-shape"
geometry = json.loads(subprocess.check_output([
    "node", "-e", "const {A,B}=require('./congruence-math');"
    "console.log(JSON.stringify({A,B,T:require('./math').transplant}));"
], cwd=site))
n = 12


def assemble(tiles):
    node_ids, tile_nodes = {}, []
    edges, row, col, stiffness, mass = Counter(), [], [], [], []
    for vertices in np.asarray(tiles):
        local = {}
        for i in range(n + 1):
            for j in range(n + 1 - i):
                key = tuple(np.round(((n-i-j)*vertices[0] + i*vertices[1] + j*vertices[2])/n, 9))
                local[i, j] = node_ids.setdefault(key, len(node_ids))
        tile_nodes.append(list(local.values()))
        for i in range(n):
            for j in range(n-i):
                cells = [[(i,j), (i+1,j), (i,j+1)]]
                if i+j+1 < n:
                    cells.append([(i+1,j), (i+1,j+1), (i,j+1)])
                for cell in cells:
                    ids = [local[p] for p in cell]
                    v = np.array([vertices[0] + (x*(vertices[1]-vertices[0]) + y*(vertices[2]-vertices[0]))/n for x,y in cell])
                    area = abs(np.linalg.det(v[1:]-v[0]))/2
                    gradients = np.linalg.inv(np.column_stack((np.ones(3), v)))[1:, :]
                    k = area * gradients.T @ gradients
                    for a, ia in enumerate(ids):
                        edges[tuple(sorted((ia, ids[(a+1)%3])))] += 1
                        for b, ib in enumerate(ids):
                            row.append(ia)
                            col.append(ib)
                            stiffness.append(k[a,b])
                            mass.append(area/3 if a == b else 0)
    boundary = {p for edge,count in edges.items() if count == 1 for p in edge}
    free = sorted(set(node_ids.values()) - boundary)
    def matrix(values):
        return coo_matrix((values, (row,col))).tocsr()[free][:,free]
    return matrix(stiffness), matrix(mass), free, np.array(tile_nodes), len(node_ids)


ka, ma, free_a, nodes_a, count_a = assemble(geometry["A"])
values, vectors = eigsh(ka, k=3, M=ma, sigma=0, v0=np.ones(len(free_a)))
mode = vectors[:, np.argsort(values)[1]]
eigenvalue = float(sorted(values)[1])
source = np.zeros(count_a)
source[free_a] = mode / mode[np.argmax(abs(mode))]
tiles = np.round(source[nodes_a], 9)
target = np.array(geometry["T"]) @ tiles
kb, mb, free_b, nodes_b, count_b = assemble(geometry["B"])
whole = np.zeros(count_b)
whole[nodes_b.ravel()] = target.ravel()
assert np.max(abs(whole[nodes_b]-target)) < 1e-8  # both sides of every seam
assert np.max(abs(np.delete(whole,free_b))) < 1e-8
v = whole[free_b]
relative_residual = np.linalg.norm(kb@v-eigenvalue*(mb@v))/np.linalg.norm(kb@v)
assert relative_residual < 1e-6
data = dict(divisions=n, eigenvalue=eigenvalue, tiles=tiles.tolist())
(site / "transplant-sample.js").write_text(
    "// Generated by _checks/drum-transplant-sample.py. Row i stores j=0 through n-i.\n"
    + "window.DrumTransplantSample = " + json.dumps(data,separators=(',',':')) + ";\n")
print(f"Mode 2, lambda_h={eigenvalue:.6f}, transferred residual={relative_residual:.2e}")
